func sameInts(a, b []int) bool {
	if len(a) != len(b) {
		return false
	}
	for i := range a {
		if a[i] != b[i] {
			return false
		}
	}
	return true
}

func sameSpans(a, b [][2]int) bool {
	if len(a) != len(b) {
		return false
	}
	for i := range a {
		if a[i] != b[i] {
			return false
		}
	}
	return true
}

func sameStrings(a, b []string) bool {
	if len(a) != len(b) {
		return false
	}
	for i := range a {
		if a[i] != b[i] {
			return false
		}
	}
	return true
}

// checkAll compares every operation on one case with CPython's results.
func checkAll(t *testing.T, label string, re *Regexp, in string, search []int, all [][2]int, sub string, split []string) {
	t.Helper()
	if got := re.FindSubmatchIndex(in); !sameInts(got, search) {
		t.Errorf("%s: FindSubmatchIndex(%q) = %v, CPython %v", label, in, got, search)
	}
	if got := re.MatchString(in); got != (search != nil) {
		t.Errorf("%s: MatchString(%q) = %v, CPython %v", label, in, got, search != nil)
	}
	if search != nil {
		if got := re.FindIndex(in); !sameInts(got, search[:2]) {
			t.Errorf("%s: FindIndex(%q) = %v, CPython %v", label, in, got, search[:2])
		}
	}
	got := re.FindAllIndex(in, -1)
	var gotSpans [][2]int
	for _, g := range got {
		gotSpans = append(gotSpans, [2]int{g[0], g[1]})
	}
	if !sameSpans(gotSpans, all) {
		t.Errorf("%s: FindAllIndex(%q) = %v, CPython %v", label, in, gotSpans, all)
	}
	if got := re.Sub("<R>", in); got != sub {
		t.Errorf("%s: Sub(%q) = %q, CPython %q", label, in, got, sub)
	}
	if split != nil {
		if got := re.Split(in, 0); !sameStrings(got, split) {
			t.Errorf("%s: Split(%q) = %q, CPython %q", label, in, got, split)
		}
	}
}

