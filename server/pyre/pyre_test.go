// ---- Compile-time rejection ----

// TestUnsupportedPatternsPanic checks that constructs outside the supported
// subset fail loudly rather than matching differently.
func TestUnsupportedPatternsPanic(t *testing.T) {
	bad := []string{
		`(?<!a+)b`,       // variable-width lookbehind
		`(a)\1`,          // backreference
		`(?P<n>a)(?P=n)`, // named backreference
		`a++`,            // possessive quantifier
		`a*+`,            // possessive quantifier
		`\N{DASH}`,       // named character
		`\q`,             // unknown ASCII escape
		`\8`,             // group reference
		`\0`,             // octal escape
		`[a`,             // unterminated class
		`a(b`,            // missing )
		`a)`,             // unbalanced )
		`a{3,2}`,         // min > max
		`*a`,             // nothing to repeat
		`a**`,            // multiple repeat
		`(?i:a)`,         // scoped flags
		`a(?i)b`,         // global flag not at start
		`(?x)a b`,        // verbose mode
		`[z-a]`,          // bad range
		`[\d-z]`,         // range starting at a class
		`[\A]`,           // anchor inside a class
		`(?u`,            // unterminated group
		`\x4`,            // short hex escape
		`\U00110000`,     // out of range
		`(?#a`,           // unterminated comment
		`x\`,             // trailing backslash
		`(?=a)*`,         // quantified lookahead
		`^*`,             // quantified anchor
		`(?P<>a)`,        // empty group name
		`(?<name>a)`,     // not Python syntax
	}
	for _, p := range bad {
		p := p
		func() {
			defer func() {
				if recover() == nil {
					t.Errorf("MustCompile(%q) did not panic", p)
				}
			}()
			MustCompile(p)
		}()
	}
}

