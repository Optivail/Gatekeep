// TestEngineSweep runs every regex that backend/engines compiles on the
// generated corpus. The expected values are CPython's, committed as JSON lines.
func TestEngineSweep(t *testing.T) {
	f, err := os.Open("testdata/engine_sweep.txt")
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()
	cache := map[string]*Regexp{}
	n := 0
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 1<<20), 1<<20)
	for sc.Scan() {
		line := sc.Text()
		if line == "" || line[0] == '#' {
			continue
		}
		var row engineSweepRow
		if err := json.Unmarshal([]byte(line), &row); err != nil {
			t.Fatalf("bad sweep row: %v", err)
		}
		key := strconv.Itoa(row.Flags) + "\x00" + row.Pat
		re := cache[key]
		if re == nil {
			re = MustCompile(row.Pat, Flags(row.Flags))
			cache[key] = re
		}
		checkAll(t, fmt.Sprintf("sweep %q flags=%d", row.Pat, row.Flags), re, row.In,
			row.Search, row.All, row.Sub, row.Split)
		n++
	}
	if err := sc.Err(); err != nil {
		t.Fatal(err)
	}
	if n < 1000 {
		t.Fatalf("sweep has only %d rows", n)
	}
	t.Logf("sweep rows checked: %d, distinct patterns: %d", n, len(cache))
}

// TestEnginesAgree checks that RE2 and regexp2 give the same submatch spans
// wherever RE2 is used. The regexp2 path is the reference for every pattern.
func TestEnginesAgree(t *testing.T) {
	inputs := []string{"", "a", "a\n", "abxd", "ab́c", "x  \n\ny", "Traceback (most recent call last):\nE: 1\n", "一 é", "ab  cd\tef\n\n\n"}
	for _, c := range cpythonCases {
		inputs = append(inputs, c.in)
	}
	checked := 0
	for _, c := range cpythonCases {
		re := MustCompile(c.pat, c.flags)
		if re.re2 == nil {
			continue
		}
		bt := &Regexp{pat: re.pat, btSrc: re.btSrc, ncap: re.ncap, bt: re.bt}
		for _, in := range inputs {
			a, b := re.FindSubmatchIndex(in), bt.FindSubmatchIndex(in)
			if !sameInts(a, b) {
				t.Errorf("%q flags=%d on %q: RE2 %v, regexp2 %v", c.pat, c.flags, in, a, b)
			}
			checked++
		}
	}
	if checked == 0 {
		t.Fatal("no RE2-eligible patterns were compared")
	}
}

// ---- Unicode class proof ----

// loadUnicodeTable reads testdata/unicode_classes.txt directly, without the
// package's own parser, so the proof does not depend on the code it checks.
func loadUnicodeTable(t *testing.T) map[string][]span {
	t.Helper()
	raw, err := os.ReadFile("testdata/unicode_classes.txt")
	if err != nil {
		t.Fatal(err)
	}
	out := map[string][]span{}
	for _, line := range strings.Split(string(raw), "\n") {
		if line == "" || line[0] == '#' {
			continue
		}
		name, rest, _ := strings.Cut(line, " ")
		for _, f := range strings.Fields(rest) {
			lo, hi, _ := strings.Cut(f, "-")
			l, _ := strconv.ParseUint(lo, 16, 32)
			h, _ := strconv.ParseUint(hi, 16, 32)
			out[name] = append(out[name], span{rune(l), rune(h)})
		}
	}
	return out
}

// allCodePoints returns every code point except surrogates, in order, as a
// valid UTF-8 string, and the code point list.
func allCodePoints() (string, []rune) {
	var b strings.Builder
	cps := make([]rune, 0, 0x110000)
	for c := rune(0); c <= maxRune; c++ {
		if c >= 0xD800 && c <= 0xDFFF {
			continue
		}
		b.WriteRune(c)
		cps = append(cps, c)
	}
	return b.String(), cps
}

// matchedRunes returns the code points that re matches one by one in big.
func matchedRunes(re *Regexp, big string) []rune {
	var out []rune
	for _, sp := range re.FindAllIndex(big, -1) {
		r, _ := utf8.DecodeRuneInString(big[sp[0]:])
		out = append(out, r)
	}
	return out
}

func expandSpans(sp []span) []rune {
	var out []rune
	for _, s := range sp {
		for c := s.lo; c <= s.hi; c++ {
			out = append(out, c)
		}
	}
	return out
}

// TestUnicodeClassesExhaustive runs \w \d \s and their negations over every
// code point (surrogates excluded) and compares the matches with CPython's
// membership in testdata/unicode_classes.txt.
func TestUnicodeClassesExhaustive(t *testing.T) {
	table := loadUnicodeTable(t)
	big, all := allCodePoints()
	inTable := func(name string) []rune { return expandSpans(table[name]) }
	complementOf := func(name string) []rune {
		in := map[rune]bool{}
		for _, c := range inTable(name) {
			in[c] = true
		}
		var out []rune
		for _, c := range all {
			if !in[c] {
				out = append(out, c)
			}
		}
		return out
	}
	cases := []struct {
		pat  string
		want []rune
	}{
		{`\w`, inTable("W")},
		{`\W`, complementOf("W")},
		{`\d`, inTable("D")},
		{`\D`, complementOf("D")},
		{`\s`, inTable("S")},
		{`\S`, complementOf("S")},
		// Each class also has to work inside a bracket.
		{`[\w]`, inTable("W")},
		{`[^\W]`, inTable("W")},
	}
	for _, c := range cases {
		got := matchedRunes(MustCompile(c.pat), big)
		if !runesEqual(got, c.want) {
			t.Errorf("%s: %d matches, CPython table %d; first difference %s",
				c.pat, len(got), len(c.want), firstDiff(got, c.want))
		} else {
			t.Logf("%s agrees with CPython on all %d code points", c.pat, len(all))
		}
	}
}

// TestBoundaryExhaustive checks \b. The input is 'A' c 'A' for each code
// point c, so the boundary at either side of c depends on c alone. CPython's
// result for each c is in the table as B (c is non-word).
func TestBoundaryExhaustive(t *testing.T) {
	table := loadUnicodeTable(t)
	bset := map[rune]bool{}
	for _, c := range expandSpans(table["B"]) {
		bset[c] = true
	}
	_, cps := allCodePoints()
	var b strings.Builder
	var want []int
	for _, c := range cps {
		b.WriteByte('A')
		start := b.Len()
		b.WriteRune(c)
		if bset[c] {
			want = append(want, start, b.Len())
		}
	}
	b.WriteByte('A')
	sep := b.String()
	// Position 0 and the end are boundaries, since the outer letters are word.
	want = append([]int{0}, append(want, len(sep))...)
	sort.Ints(want)

	var got []int
	for _, sp := range MustCompile(`\b`).FindAllIndex(sep, -1) {
		if sp[0] != sp[1] {
			t.Fatalf("\\b matched non-empty span %v", sp)
		}
		got = append(got, sp[0])
	}
	if !sameInts(got, want) {
		t.Fatalf("\\b boundaries: got %d positions, CPython table gives %d", len(got), len(want))
	}
	t.Logf("\\b agrees with CPython on all %d code points (%d boundary positions)", len(cps), len(got))
}

func runesEqual(a, b []rune) bool {
	if len(a) != len(b) {
		return false
	}
	for i := range a {
		if a[i] != b[i] {
			return false
		}
	}
	return true
}

func firstDiff(got, want []rune) string {
	for i := 0; i < len(got) || i < len(want); i++ {
		var g, w any = "-", "-"
		if i < len(got) {
			g = fmt.Sprintf("U+%04X", got[i])
		}
		if i < len(want) {
			w = fmt.Sprintf("U+%04X", want[i])
		}
		if fmt.Sprint(g) != fmt.Sprint(w) {
			return fmt.Sprintf("at %d: got %v want %v", i, g, w)
		}
	}
	return "none"
}

// ---- IGNORECASE proof ----

// TestIgnoreCaseSample checks, for a sample of code points, that a literal
// with IgnoreCase matches exactly CPython's equivalence class. The classes
// are CPython's exhaustive measurement in testdata/casefold_classes.txt.
func TestIgnoreCaseSample(t *testing.T) {
	raw, err := os.ReadFile("testdata/casefold_classes.txt")
	if err != nil {
		t.Fatal(err)
	}
	class := map[rune]int{}
	gid := 0
	for _, line := range strings.Split(string(raw), "\n") {
		if line == "" || line[0] == '#' {
			continue
		}
		gid++
		for _, f := range strings.Fields(line) {
			v, _ := strconv.ParseUint(f, 16, 32)
			class[rune(v)] = gid
		}
	}
	var sample []rune
	add := func(lo, hi rune) {
		for c := lo; c <= hi; c++ {
			sample = append(sample, c)
		}
	}
	add(0x00, 0x7F)
	add(0x80, 0xFF)
	add(0x370, 0x3FF)
	add(0x400, 0x4FF)
	sample = append(sample, 0x130, 0x131, 0x17F, 0x212A, 0x212B, 0x1E9E, 0x1E9B, 0x1E61, 0x3C2, 0x2126, 0x1C5)
	pairs := 0
	for _, a := range sample {
		re := MustCompile(fmt.Sprintf(`\U%08X`, a), IgnoreCase)
		for _, b := range sample {
			want := a == b || (class[a] != 0 && class[a] == class[b])
			got := re.MatchString(string(b))
			if got != want {
				t.Errorf("re.I: U+%04X vs U+%04X: pyre %v, CPython %v", a, b, got, want)
			}
			pairs++
		}
	}
	t.Logf("IGNORECASE pairs checked: %d over %d code points", pairs, len(sample))
}

