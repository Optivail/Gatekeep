#!/usr/bin/env python3
"""Emit CPython 3 regex character-class tables for the Go package server/pyre.

Run with CPython (no third-party deps):

    python3 -I server/parity/gen_unicode.py

It writes two committed files next to the pyre package:

  testdata/unicode_classes.txt   membership of every code point (0x0..0x10FFFF,
                                 surrogates excluded) in CPython's \\w, \\d, \\s
                                 and in the set of code points that make \\b
                                 hold between an ASCII 'A' and that code point.
  testdata/casefold_classes.txt  IGNORECASE equivalence classes: every group of
                                 code points that re.fullmatch(escape(a), b, re.I)
                                 treats as equal.

Everything is measured with the running interpreter, so the tables reflect its
own Unicode database; the output records the version so a change is visible.
"""
import os
import re
import sys
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "pyre", "testdata")
MAXCP = 0x110000


def is_surrogate(c):
    return 0xD800 <= c <= 0xDFFF


def ranges(cps):
    """Collapse a sorted iterable of code points into inclusive (lo, hi) runs."""
    out = []
    for c in cps:
        if out and out[-1][1] == c - 1:
            out[-1][1] = c
        else:
            out.append([c, c])
    return out


def fmt(rs):
    return " ".join("%04X-%04X" % (lo, hi) for lo, hi in rs)


def class_tables():
    cps = [c for c in range(MAXCP) if not is_surrogate(c)]
    # One big str holds every code point; findall reports code point indices
    # directly because str indices are code points. Surrogates are left out
    # of the text so the Go side (valid UTF-8 only) can use the same input.
    big = "".join(chr(c) for c in cps)
    index_to_cp = cps
    w = {index_to_cp[m.start()] for m in re.finditer(r"\w", big)}
    d = {index_to_cp[m.start()] for m in re.finditer(r"\d", big)}
    s = {index_to_cp[m.start()] for m in re.finditer(r"\s", big)}
    # \b is a position property. Surround each code point with 'A' so the
    # boundary on each side of it depends only on that code point. The
    # boundary positions are then measured directly on CPython's output.
    sep = "".join("A" + chr(c) + "A" for c in cps)
    bpos = {m.start() for m in re.finditer(r"\b", sep)}
    b = set()
    for k, c in enumerate(cps):
        left = 3 * k + 1  # between 'A' and c
        right = 3 * k + 2  # between c and 'A'
        if left in bpos and right in bpos:
            b.add(c)
    # Sanity: the boundary test must also agree with the \w table.
    for c in cps:
        if (c in b) == (c in w):
            raise SystemExit("unexpected \\b/\\w relation at U+%04X" % c)
    return w, d, s, b


def write_unicode_classes(w, d, s, b):
    path = os.path.join(OUT, "unicode_classes.txt")
    with open(path, "w", encoding="ascii", newline="\n") as f:
        f.write("# CPython %s, Unicode %s. Generated by server/parity/gen_unicode.py.\n"
                % (sys.version.split()[0], unicodedata.unidata_version))
        f.write("# Code points are hex, inclusive ranges, surrogates excluded.\n")
        f.write("# W: \\w   D: \\d   S: \\s   B: code point makes \\b hold between 'A' and it.\n")
        for name, S in (("W", w), ("D", d), ("S", s), ("B", b)):
            f.write("%s %s\n" % (name, fmt(ranges(sorted(S)))))
    return path


def casefold_groups():
    """IGNORECASE classes. A code point can match another only through its
    case mappings or through CPython's extra-case table (re._casefix, 3.11+),
    so the candidates are: every code point that lower(), upper(), title() or
    casefold() changes, the extra-case table, and everything those mappings
    produce, closed to a fixed point. Any other code point matches only itself.
    For each candidate, the full code point range is scanned for matches."""
    from re._casefix import _EXTRA_CASES

    def images(c):
        s = chr(c)
        out = set()
        for f in (str.lower, str.upper, str.title, str.casefold):
            r = f(s)
            if r != s:
                out.update(ord(x) for x in r)
        return out

    cand = set()
    for c in range(MAXCP):
        if not is_surrogate(c) and images(c):
            cand.add(c)
    for k, vs in _EXTRA_CASES.items():
        cand.add(k)
        cand.update(vs)
    frontier = set(cand)
    while frontier:
        nxt = set()
        for c in frontier:
            for v in images(c):
                if v not in cand and not is_surrogate(v):
                    cand.add(v)
                    nxt.add(v)
        frontier = nxt

    cps = [c for c in range(MAXCP) if not is_surrogate(c)]
    big = "".join(chr(c) for c in cps)
    classes = {}
    for a in sorted(cand):
        matched = frozenset(cps[m.start()] for m in re.finditer(re.escape(chr(a)), big, re.I))
        classes[a] = matched
    # Each match set must be an equivalence class: members agree on their own sets.
    groups = {}
    for a, mset in classes.items():
        if a not in mset:
            raise SystemExit("U+%04X does not match itself" % a)
        key = min(mset)
        if key in groups and groups[key] != mset:
            raise SystemExit("IGNORECASE relation is not an equivalence at U+%04X" % a)
        groups[key] = mset
    for key, mset in groups.items():
        for b in mset:
            if b in classes and classes[b] != mset:
                raise SystemExit("IGNORECASE classes disagree at U+%04X" % b)
    multi = sorted(sorted(m) for m in groups.values() if len(m) > 1)
    return multi, len(cand)


def write_casefold(multi, ncand):
    path = os.path.join(OUT, "casefold_classes.txt")
    with open(path, "w", encoding="ascii", newline="\n") as f:
        f.write("# IGNORECASE equivalence classes measured with CPython %s (Unicode %s).\n"
                % (sys.version.split()[0], unicodedata.unidata_version))
        f.write("# One group per line; every code point in a group matches every other under re.I.\n")
        f.write("# Code points not listed match only themselves.\n")
        for g in multi:
            f.write(" ".join("%04X" % c for c in g) + "\n")
    return path, ncand


if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    w, d, s, b = class_tables()
    p1 = write_unicode_classes(w, d, s, b)
    print("wrote", os.path.basename(p1), "W=%d D=%d S=%d B=%d" % (len(w), len(d), len(s), len(b)))
    multi, ncand = casefold_groups()
    p2, _ = write_casefold(multi, ncand)
    print("wrote", os.path.basename(p2), "groups=%d candidates=%d" % (len(multi), ncand))
